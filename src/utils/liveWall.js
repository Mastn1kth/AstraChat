// Mulberry32: tiny seeded PRNG so the matrix stays stable within a session
// but differs between visits.
function createRandom(seed) {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function sampleLibraryWords(count, seed = Date.now()) {
  const random = createRandom(seed)
  const pool = [...WORD_LIBRARY]
  const picked = []
  while (picked.length < count && pool.length) {
    const index = Math.floor(random() * pool.length)
    picked.push(pool.splice(index, 1)[0])
  }
  return picked
}

// Matrix mode: every word from every message the client can see, no filtering.
// This stays strictly local because only this browser has the local message keys.
export function extractAllChatWords(messagesByChat) {
  const words = []
  const seen = new Set()
  Object.values(messagesByChat || {}).forEach((messages) => {
    if (!Array.isArray(messages)) return
    messages.forEach((message) => {
      if (message.deleted || typeof message.text !== 'string') return
      const tokens = message.text.match(/\S{1,24}/gu) || []
      tokens.forEach((token) => {
        const key = token.toLocaleLowerCase()
        if (seen.has(key)) return
        seen.add(key)
        words.push(token)
      })
    })
  })
  return words.slice(-400)
}
